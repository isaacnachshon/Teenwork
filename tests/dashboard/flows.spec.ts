test('teen can search open a job and apply through the active layout',async({page})=>{
 await page.goto('/?role=teen');
 await expect(page.getByRole('button',{name:'ניהול משרות',exact:true})).toHaveCount(0);
 await page.getByRole('button',{name:'חיפוש משרות',exact:true}).click();
 await expect(page.getByRole('heading',{name:'משרה לדוגמה',exact:true})).toBeVisible();
 await expect(page.getByText('שכר ושעות לפי חוק ✓').first()).toBeVisible();
 await page.getByRole('button',{name:'צפה בפרטים',exact:true}).first().click();
 await expect(page.getByRole('region',{name:'זכויות במשרה זו'})).toContainText('שכר ₪45 לשעה');
 await expect(page.getByRole('button',{name:'הגש מועמדות עכשיו',exact:true})).toBeEnabled();
 await page.getByRole('button',{name:'הגש מועמדות עכשיו',exact:true}).click();
 await expect(page.getByRole('button',{name:'המועמדות נשלחה ✓',exact:true})).toBeDisabled();
 expect(await page.evaluate(()=>(window as any).testStore.applications.added.jobId)).toBe('first');
 await page.getByRole('button',{name:'חזרה לחיפוש',exact:true}).click();
 await expect(page.getByRole('button',{name:'צפה בפרטים',exact:true}).first()).toBeVisible();
});
test('teen cannot apply to a job that breaks the youth law for their age',async({page})=>{
 await page.goto('/?role=teen');
 await page.getByRole('button',{name:'חיפוש משרות',exact:true}).click();
 await expect(page.getByText('לא עומד בחוק עבודת הנוער')).toBeVisible();
 await page.locator('h3:has-text("משרה לא חוקית")').locator('xpath=ancestor::div[contains(@class,"rounded-xl")][1]').getByRole('button',{name:'צפה בפרטים',exact:true}).click();
 const panel=page.getByRole('region',{name:'זכויות במשרה זו'});
 await expect(panel).toContainText('נמוך משכר המינימום לגילך');
 await expect(panel).toContainText('חורגות מהמותר לגילך');
 await expect(page.getByRole('button',{name:'הגש מועמדות עכשיו',exact:true})).toBeDisabled();
 await expect(page.getByRole('alert').first()).toContainText('שכר המינימום לגילך');
});
