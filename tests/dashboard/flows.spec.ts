import {test,expect} from '@playwright/test';
test('completed employment exposes ratings and related profiles',async({page})=>{
 await page.goto('/');
 await page.evaluate(()=>{(window as any).testStore.applications.a.status='completed'});
 await page.getByRole('button',{name:'מועמדים והעסקות',exact:true}).click();
 await page.getByRole('button',{name:'פרטים',exact:true}).click();
 await expect(page.getByRole('dialog',{name:'פרטי ההתקשרות'})).toContainText('מועמד בדיקה');
 await page.getByRole('button',{name:'דרג עובד',exact:true}).click();
 await page.getByRole('combobox').selectOption('4');
 await page.getByRole('button',{name:'שמור דירוג',exact:true}).click();
 expect(await page.evaluate(()=>(window as any).rating)).toEqual({applicationId:'a',score:4});
 await page.getByRole('button',{name:'דירוגים',exact:true}).click();
 await expect(page.getByText('עסק בדיקה — 4.5 מתוך 5 · 2 דירוגים')).toBeVisible();
 await expect(page.getByText('מועמד בדיקה — 5.0 מתוך 5 · 1 דירוגים')).toBeVisible();
});
